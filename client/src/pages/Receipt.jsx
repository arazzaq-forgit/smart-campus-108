import { useEffect, useState } from 'react';
import { Link, useParams } from 'react-router-dom';
import api from '../api';
import { Empty, Spinner, fmtDate, inr } from '../components/ui';

export default function Receipt() {
  const { id } = useParams();
  const [d, setD] = useState(null), [missing, setMissing] = useState(false);
  useEffect(() => { api.get(`/bookings/${id}`).then(r => setD(r.data)).catch(() => setMissing(true)); }, [id]);
  if (missing) return <div className="wrap page"><Empty icon="🧾" title="Receipt not found" action={<Link className="btn" to="/my-bookings">Back to bookings</Link>} /></div>;
  if (!d) return <div className="wrap page"><Spinner /></div>;
  const { booking: b, payment: p } = d;
  const rows = [
    ['Receipt no.', '#' + b._id.slice(-8).toUpperCase()],
    ['Student', `${b.user?.name} (${b.user?.email})`],
    ['Service', `${b.service?.name} · ${b.service?.category}`],
    ['Date and slot', `${fmtDate(b.date)} · ${b.slot}`],
    ['Booking status', b.status],
    ['Payment status', b.paymentStatus],
    ['Payment reference', p?.paymentId || '-'],
    ['Paid on', p?.paidAt ? new Date(p.paidAt).toLocaleString('en-IN') : '-']
  ];
  return (
    <div className="wrap page receipt-page">
      <div className="receipt">
        <div className="receipt-head"><h1>Campus Desk</h1><span>Payment receipt</span></div>
        <dl>{rows.map(([k, v]) => <div key={k}><dt>{k}</dt><dd>{v}</dd></div>)}</dl>
        <div className="receipt-total"><span>Amount</span><b>{inr(b.amount)}</b></div>
        <p className="muted">Generated by the Smart Campus Service Booking and Management System.</p>
      </div>
      <div className="receipt-actions no-print">
        <Link className="btn ghost" to="/my-bookings">Back</Link>
        <button className="btn" onClick={() => window.print()}>Print or save as PDF</button>
      </div>
    </div>
  );
}
